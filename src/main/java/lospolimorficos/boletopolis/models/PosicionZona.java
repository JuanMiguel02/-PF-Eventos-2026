package lospolimorficos.boletopolis.models;

/**
 * Enumeración que define las posibles posiciones de una zona dentro de un recinto.
 * Estas posiciones son direccionales (Norte, Sur, Este, Oeste).
 */
public enum PosicionZona {
    /**
     * Posición Norte.
     */
    NORTE,
    /**
     * Posición Sur.
     */
    SUR,
    /**
     * Posición Este.
     */
    ESTE,
    /**
     * Posición Oeste.
     */
    OESTE;
}
