package lospolimorficos.boletopolis.models;

/**
 * Enumeración que define las posibles posiciones de un escenario dentro de un recinto.
 */
public enum PosicionEscenario {
    /**
     * El escenario está ubicado en la parte superior del recinto.
     */
    ARRIBA,
    /**
     * El escenario está ubicado en la parte inferior del recinto.
     */
    ABAJO,
    /**
     * El escenario está ubicado a la izquierda del recinto.
     */
    IZQUIERDA,
    /**
     * El escenario está ubicado a la derecha del recinto.
     */
    DERECHA,
    /**
     * El escenario está ubicado en el centro del recinto.
     */
    CENTRO;
}
